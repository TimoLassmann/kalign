"""Generate lib/src/aln_wave.c from the validated harness kernels.

The wavefront DP passes are developed and checked bit-for-bit in the
harness (perf/dp/kernels/{ss,sp,pp}_wave.c, bench_dp --check).  This script
copies their sweep code into the library unchanged, except for:
  - per-alignment tables taken from m->wave instead of kdp_kernel_state,
  - thread-local scratch (forward and backward can run on different threads),
  - renamed seq-profile internals (they share names with the seq-seq code).

usage (from the repository root):
    uv run --no-project python perf/dp/tools/gen_aln_wave.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
K = ROOT / "perf/dp/kernels"


def between(s, a, b):
    i = s.index(a)
    return s[i:s.index(b, i)]


def main():
    ss = (K / "ss_wave.c").read_text()
    sp = (K / "sp_wave.c").read_text()
    pp = (K / "pp_wave.c").read_text()

    ss_prep = between(ss, "struct sw_state {", "struct sw_buf {")
    ss_body = between(ss, "struct sw_buf {", "static int sw_fwd(")
    ss_body = ss_body.replace("static struct sw_buf wb = {0};",
                              "static _Thread_local struct sw_buf wb = {0};")
    ss_body = ss_body.replace("const struct sw_state* st = kdp_kernel_state;",
                              "const struct sw_state* st = ((const struct aln_wave*)m->wave)->ss;")

    sp_body = between(sp, "struct sw_buf {", "static int spw_fwd(")
    for a, b in [("struct sw_buf", "struct spw_buf"),
                 ("static struct spw_buf wb = {0};", "static _Thread_local struct spw_buf spb = {0};"),
                 ("sw_reserve", "spw_reserve"), ("sw_sweep", "spw_sweep"), ("wb.", "spb.")]:
        sp_body = sp_body.replace(a, b)

    pp_prep = between(pp, "struct pw_state {", "struct pw_buf {")
    pp_body = between(pp, "struct pw_buf {", "static int pw_fwd(")
    pp_body = pp_body.replace("static struct pw_buf pb = {0};",
                              "static _Thread_local struct pw_buf pb = {0};")
    pp_body = pp_body.replace("const struct pw_state* st = kdp_kernel_state;",
                              "const struct pw_state* st = ((const struct aln_wave*)m->wave)->pp;")

    for body, name in ((ss_body, "ss"), (sp_body, "sp"), (pp_body, "pp")):
        assert "kdp_kernel_state" not in body, name
        assert "_Thread_local" in body, name

    out = HEAD + ss_prep + ss_body + pp_prep + pp_body + \
        "\n/* ---- seq-profile ---- */\n" + sp_body + TAIL
    (ROOT / "lib/src/aln_wave.c").write_text(out)
    print("wrote lib/src/aln_wave.c")


HEAD = '''/* aln_wave.c -- wavefront SIMD DP passes (built with -DKALIGN_WAVE, the default).
 *
 * GENERATED by perf/dp/tools/gen_aln_wave.py from the harness kernels
 * perf/dp/kernels/{ss,sp,pp}_wave.c (validated bit-for-bit with bench_dp
 * --check).  Edit the kernels and regenerate; do not edit this file.
 *
 * Inter-row wavefront SIMD (NEON or AVX2, lib/src/wave_simd.h) forward/backward
 * passes for the seq-seq,
 * seq-profile and profile-profile DP, bit-identical to aln_seqseq.c,
 * aln_seqprofile.c and aln_profileprofile.c.  Per-alignment column tables
 * are owned by m->wave (built in aln_runner for a top-level call); scratch is
 * thread-local, since the forward and backward pass of one call can run on
 * different threads.  Builds without NEON or AVX2 use the scalar kernels.
 */
#ifdef KALIGN_WAVE
#include <float.h>
#include <math.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "tldevel.h"
#include "aln_param.h"
#include "aln_struct.h"
#include "anchor_consistency.h"

#define ALN_WAVE_IMPORT
#include "aln_wave.h"

#undef MAX
#undef MAX3
#define MAX(a, b) ((a) > (b) ? (a) : (b))
#define MAX3(a, b, c) MAX(MAX(a, b), c)

#include "wave_simd.h"

#define KDP_SS 0
#define KDP_PP 2

#if WAVE_SIMD

#define SW_MIN_W 16
#define PW_MIN_W 16
#define QPAD 32
#define WAVE_PART_MIN 3
#define WL 8

struct sw_state;
struct pw_state;
struct aln_wave {
        struct sw_state* ss;
        struct pw_state* pp;
        int sp;
};

'''

TAIL = '''
int aln_wave_prepare(struct aln_mem* m)
{
        struct aln_wave* w;
        void* st = NULL;
        if(m->wave) return 0;
        if(m->seq1){
                sw_prepare(m, KDP_SS, &st);
                if(!st) return 0;
        }else if(m->prof2){
                pw_prepare(m, KDP_PP, &st);
                if(!st) return 0;
        }
        w = calloc(1, sizeof(*w));
        if(!w){
                if(m->seq1) sw_release(st); else if(m->prof2) pw_release(st);
                return 0;
        }
        if(m->seq1) w->ss = st; else if(m->prof2) w->pp = st; else w->sp = 1;
        m->wave = w;
        return 1;
}

void aln_wave_free(struct aln_mem* m)
{
        struct aln_wave* w = m->wave;
        if(!w) return;
        sw_release(w->ss);
        pw_release(w->pp);
        free(w);
        m->wave = NULL;
}

int aln_wave_ss(struct aln_mem* m, int dir)
{
        const struct aln_wave* w = m->wave;
        if(!w || !w->ss || m->endb - m->startb - 1 < SW_MIN_W) return 1;
        if(dir > 0){
                if(m->enda <= m->starta) return 1;
                return sw_sweep(m, 1);
        }
        if(m->enda_2 <= m->starta_2) return 1;
        return sw_sweep(m, -1);
}

int aln_wave_pp(struct aln_mem* m, int dir)
{
        const struct aln_wave* w = m->wave;
        if(!w || !w->pp || m->endb - m->startb - 1 < PW_MIN_W) return 1;
        if(dir > 0){
                if(m->enda <= m->starta) return 1;
                return pw_sweep(m, 1);
        }
        if(m->enda_2 <= m->starta_2) return 1;
        return pw_sweep(m, -1);
}

int aln_wave_sp(struct aln_mem* m, int dir)
{
        const struct aln_wave* w = m->wave;
        if(!w || !w->sp || m->endb - m->startb - 1 < SW_MIN_W) return 1;
        if(dir > 0){
                if(m->enda <= m->starta) return 1;
                return spw_sweep(m, 1);
        }
        if(m->enda_2 <= m->starta_2) return 1;
        return spw_sweep(m, -1);
}

#else

int aln_wave_prepare(struct aln_mem* m) { (void)m; return 0; }
void aln_wave_free(struct aln_mem* m) { (void)m; }
int aln_wave_ss(struct aln_mem* m, int dir) { (void)m; (void)dir; return 1; }
int aln_wave_pp(struct aln_mem* m, int dir) { (void)m; (void)dir; return 1; }
int aln_wave_sp(struct aln_mem* m, int dir) { (void)m; (void)dir; return 1; }

#endif /* WAVE_SIMD */
#else
typedef int aln_wave_unused_t;
#endif /* KALIGN_WAVE */
'''

if __name__ == "__main__":
    main()
